CREATE TABLE MENSAGENS_PROCESSADAS (
    ID_MENSAGEM     VARCHAR2(160 CHAR)               NOT NULL,
    ORIGEM          VARCHAR2(20 CHAR)                NOT NULL,
    CANAL           VARCHAR2(120 CHAR)               NOT NULL,
    ETAPA           VARCHAR2(40 CHAR),
    RESULTADO       VARCHAR2(20 CHAR)                NOT NULL,
    TRACEPARENT     VARCHAR2(60 CHAR),
    PROCESSADO_EM   TIMESTAMP(9) WITH TIME ZONE NOT NULL,
    CONSTRAINT PK_MENSAGENS_PROCESSADAS PRIMARY KEY (ID_MENSAGEM),
    CONSTRAINT CK_MENSAGENS_ORIGEM CHECK (ORIGEM IN ('KAFKA', 'WEBHOOK', 'API'))
);

CREATE INDEX IX_MENSAGENS_PROCESSADAS_DATA ON MENSAGENS_PROCESSADAS (PROCESSADO_EM);

CREATE TABLE EVENTOS_SAIDA (
    ID              VARCHAR2(36 CHAR)                NOT NULL,
    TIPO            VARCHAR2(80 CHAR)                NOT NULL,
    AGREGADO        VARCHAR2(40 CHAR)                NOT NULL,
    CHAVE_AGREGADO  VARCHAR2(60 CHAR)                NOT NULL,
    TOPICO          VARCHAR2(120 CHAR)               NOT NULL,
    PAYLOAD         CLOB                        NOT NULL,
    CABECALHO       CLOB,
    TRACEPARENT     VARCHAR2(60 CHAR),
    SITUACAO        VARCHAR2(20 CHAR)                NOT NULL,
    TENTATIVAS      NUMBER(10) DEFAULT 0        NOT NULL,
    ULTIMO_ERRO     VARCHAR2(500 CHAR),
    CRIADO_EM       TIMESTAMP(9) WITH TIME ZONE NOT NULL,
    PUBLICADO_EM    TIMESTAMP(9) WITH TIME ZONE,
    CONSTRAINT PK_EVENTOS_SAIDA PRIMARY KEY (ID),
    CONSTRAINT CK_EVENTOS_SAIDA_SITUACAO CHECK (SITUACAO IN ('PENDENTE', 'PUBLICADO', 'FALHO'))
);

CREATE INDEX IX_EVENTOS_SAIDA_PENDENTES ON EVENTOS_SAIDA (SITUACAO, CRIADO_EM);

CREATE INDEX IX_EVENTOS_SAIDA_AGREGADO ON EVENTOS_SAIDA (AGREGADO, CHAVE_AGREGADO);
