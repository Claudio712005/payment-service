CREATE TABLE PAGAMENTOS (
    ID                      VARCHAR2(36 CHAR)                     NOT NULL,
    ORDEM_SERVICO_ID        VARCHAR2(36 CHAR)                     NOT NULL,
    CLIENTE_ID              VARCHAR2(36 CHAR)                     NOT NULL,
    MEIO                    VARCHAR2(20 CHAR)                     NOT NULL,
    SITUACAO                VARCHAR2(20 CHAR)                     NOT NULL,
    MOEDA                   VARCHAR2(3 CHAR)   DEFAULT 'BRL'      NOT NULL,
    VALOR_TOTAL             NUMBER(15,2)                     NOT NULL,
    VALOR_PAGO              NUMBER(15,2)  DEFAULT 0          NOT NULL,
    VALOR_ESTORNADO         NUMBER(15,2)  DEFAULT 0          NOT NULL,
    QUANTIDADE_PARCELAS     NUMBER(10)    DEFAULT 1          NOT NULL,
    CHAVE_IDEMPOTENCIA      VARCHAR2(80 CHAR)                     NOT NULL,
    PROVEDOR                VARCHAR2(30 CHAR)                     NOT NULL,
    PAGAMENTO_PROVEDOR_ID   VARCHAR2(60 CHAR),
    EXPIRA_EM               TIMESTAMP(9) WITH TIME ZONE,
    CONFIRMADO_EM           TIMESTAMP(9) WITH TIME ZONE,
    MOTIVO_RECUSA           VARCHAR2(500 CHAR),
    CRIADO_EM               TIMESTAMP(9) WITH TIME ZONE      NOT NULL,
    ATUALIZADO_EM           TIMESTAMP(9) WITH TIME ZONE      NOT NULL,
    VERSAO                  NUMBER(10)    DEFAULT 0          NOT NULL,
    CONSTRAINT PK_PAGAMENTOS PRIMARY KEY (ID),
    CONSTRAINT UK_PAGAMENTOS_IDEMPOTENCIA UNIQUE (CHAVE_IDEMPOTENCIA),
    CONSTRAINT UK_PAGAMENTOS_PROVEDOR UNIQUE (PROVEDOR, PAGAMENTO_PROVEDOR_ID),
    CONSTRAINT CK_PAGAMENTOS_MEIO CHECK (MEIO IN ('PIX', 'BOLETO', 'CARTAO_CREDITO', 'CARTAO_DEBITO')),
    CONSTRAINT CK_PAGAMENTOS_SITUACAO CHECK (SITUACAO IN ('PENDENTE', 'AUTORIZADO', 'PAGO', 'RECUSADO', 'EXPIRADO', 'CANCELADO', 'ESTORNADO_PARCIAL', 'ESTORNADO_TOTAL')),
    CONSTRAINT CK_PAGAMENTOS_VALORES CHECK (VALOR_TOTAL > 0 AND VALOR_PAGO >= 0 AND VALOR_ESTORNADO >= 0 AND VALOR_ESTORNADO <= VALOR_TOTAL),
    CONSTRAINT CK_PAGAMENTOS_PARCELAS CHECK (QUANTIDADE_PARCELAS BETWEEN 1 AND 24)
);

CREATE INDEX IX_PAGAMENTOS_ORDEM ON PAGAMENTOS (ORDEM_SERVICO_ID);

CREATE INDEX IX_PAGAMENTOS_CLIENTE ON PAGAMENTOS (CLIENTE_ID);

CREATE INDEX IX_PAGAMENTOS_EXPIRACAO ON PAGAMENTOS (SITUACAO, EXPIRA_EM);

CREATE TABLE PARCELAS (
    ID              VARCHAR2(36 CHAR)    NOT NULL,
    PAGAMENTO_ID    VARCHAR2(36 CHAR)    NOT NULL,
    NUMERO          NUMBER(10)      NOT NULL,
    VALOR           NUMBER(15,2)    NOT NULL,
    SITUACAO        VARCHAR2(20 CHAR)    NOT NULL,
    VENCIMENTO      DATE,
    LIQUIDADO_EM    TIMESTAMP(9) WITH TIME ZONE,
    CONSTRAINT PK_PARCELAS PRIMARY KEY (ID),
    CONSTRAINT UK_PARCELAS_PAGAMENTO_NUMERO UNIQUE (PAGAMENTO_ID, NUMERO),
    CONSTRAINT FK_PARCELAS_PAGAMENTO FOREIGN KEY (PAGAMENTO_ID) REFERENCES PAGAMENTOS (ID),
    CONSTRAINT CK_PARCELAS_SITUACAO CHECK (SITUACAO IN ('PENDENTE', 'PAGA', 'VENCIDA', 'CANCELADA')),
    CONSTRAINT CK_PARCELAS_VALOR CHECK (VALOR > 0),
    CONSTRAINT CK_PARCELAS_NUMERO CHECK (NUMERO >= 1)
);

CREATE INDEX IX_PARCELAS_VENCIMENTO ON PARCELAS (SITUACAO, VENCIMENTO);

CREATE TABLE TRANSACOES (
    ID                      VARCHAR2(36 CHAR)    NOT NULL,
    PAGAMENTO_ID            VARCHAR2(36 CHAR)    NOT NULL,
    TIPO                    VARCHAR2(20 CHAR)    NOT NULL,
    SITUACAO                VARCHAR2(20 CHAR)    NOT NULL,
    VALOR                   NUMBER(15,2)    NOT NULL,
    TRANSACAO_PROVEDOR_ID   VARCHAR2(60 CHAR),
    CODIGO_RETORNO          VARCHAR2(40 CHAR),
    MENSAGEM_RETORNO        VARCHAR2(500 CHAR),
    MOTIVO                  VARCHAR2(500 CHAR),
    PAYLOAD_ID              VARCHAR2(60 CHAR),
    TRACEPARENT             VARCHAR2(60 CHAR),
    OCORRIDO_EM             TIMESTAMP(9) WITH TIME ZONE,
    REGISTRADO_EM           TIMESTAMP(9) WITH TIME ZONE NOT NULL,
    CONSTRAINT PK_TRANSACOES PRIMARY KEY (ID),
    CONSTRAINT FK_TRANSACOES_PAGAMENTO FOREIGN KEY (PAGAMENTO_ID) REFERENCES PAGAMENTOS (ID),
    CONSTRAINT UK_TRANSACOES_PROVEDOR UNIQUE (TIPO, TRANSACAO_PROVEDOR_ID),
    CONSTRAINT CK_TRANSACOES_TIPO CHECK (TIPO IN ('AUTORIZACAO', 'CAPTURA', 'CONFIRMACAO', 'CANCELAMENTO', 'ESTORNO')),
    CONSTRAINT CK_TRANSACOES_SITUACAO CHECK (SITUACAO IN ('SOLICITADA', 'CONFIRMADA', 'RECUSADA', 'EXPIRADA')),
    CONSTRAINT CK_TRANSACOES_VALOR CHECK (VALOR > 0)
);

CREATE INDEX IX_TRANSACOES_PAGAMENTO ON TRANSACOES (PAGAMENTO_ID, REGISTRADO_EM);
