CREATE TABLE NOTAS_FISCAIS (
    ID                      VARCHAR2(36 CHAR)                NOT NULL,
    PAGAMENTO_ID            VARCHAR2(36 CHAR)                NOT NULL,
    ORDEM_SERVICO_ID        VARCHAR2(36 CHAR)                NOT NULL,
    SITUACAO                VARCHAR2(20 CHAR)                NOT NULL,
    SERIE                   VARCHAR2(5 CHAR)                 NOT NULL,
    NUMERO                  NUMBER(19),
    CHAVE_DE_ACESSO         VARCHAR2(60 CHAR),
    CODIGO_VERIFICACAO      VARCHAR2(40 CHAR),
    CNPJ_PRESTADOR          VARCHAR2(14 CHAR)                NOT NULL,
    DOCUMENTO_TOMADOR       VARCHAR2(14 CHAR)                NOT NULL,
    MUNICIPIO_INCIDENCIA    VARCHAR2(7 CHAR)                 NOT NULL,
    COMPETENCIA             DATE                        NOT NULL,
    VALOR_SERVICOS          NUMBER(15,2)                NOT NULL,
    VALOR_INSUMOS           NUMBER(15,2) DEFAULT 0      NOT NULL,
    VALOR_DEDUCOES          NUMBER(15,2) DEFAULT 0      NOT NULL,
    BASE_DE_CALCULO         NUMBER(15,2)                NOT NULL,
    ALIQUOTA_ISS            NUMBER(7,4)                 NOT NULL,
    VALOR_ISS               NUMBER(15,2)                NOT NULL,
    VALOR_TOTAL             NUMBER(15,2)                NOT NULL,
    PROTOCOLO               VARCHAR2(60 CHAR),
    MOTIVO_REJEICAO         VARCHAR2(500 CHAR),
    MOTIVO_CANCELAMENTO     VARCHAR2(500 CHAR),
    ESPELHO_ID              VARCHAR2(60 CHAR),
    EMITIDA_EM              TIMESTAMP(9) WITH TIME ZONE,
    CANCELADA_EM            TIMESTAMP(9) WITH TIME ZONE,
    CRIADO_EM               TIMESTAMP(9) WITH TIME ZONE NOT NULL,
    ATUALIZADO_EM           TIMESTAMP(9) WITH TIME ZONE NOT NULL,
    VERSAO                  NUMBER(10) DEFAULT 0        NOT NULL,
    CONSTRAINT PK_NOTAS_FISCAIS PRIMARY KEY (ID),
    CONSTRAINT UK_NOTAS_FISCAIS_PAGAMENTO UNIQUE (PAGAMENTO_ID),
    CONSTRAINT UK_NOTAS_FISCAIS_NUMERO UNIQUE (CNPJ_PRESTADOR, SERIE, NUMERO),
    CONSTRAINT UK_NOTAS_FISCAIS_CHAVE UNIQUE (CHAVE_DE_ACESSO),
    CONSTRAINT FK_NOTAS_FISCAIS_PAGAMENTO FOREIGN KEY (PAGAMENTO_ID) REFERENCES PAGAMENTOS (ID),
    CONSTRAINT CK_NOTAS_FISCAIS_SITUACAO CHECK (SITUACAO IN ('PENDENTE', 'EM_EMISSAO', 'AUTORIZADA', 'REJEITADA', 'CANCELADA')),
    CONSTRAINT CK_NOTAS_FISCAIS_VALORES CHECK (VALOR_SERVICOS >= 0 AND VALOR_INSUMOS >= 0 AND VALOR_DEDUCOES >= 0 AND BASE_DE_CALCULO >= 0 AND VALOR_ISS >= 0 AND VALOR_TOTAL > 0),
    CONSTRAINT CK_NOTAS_FISCAIS_ALIQUOTA CHECK (ALIQUOTA_ISS >= 0 AND ALIQUOTA_ISS <= 100),
    CONSTRAINT CK_NOTAS_FISCAIS_AUTORIZADA CHECK (SITUACAO <> 'AUTORIZADA' OR (NUMERO IS NOT NULL AND EMITIDA_EM IS NOT NULL))
);

CREATE INDEX IX_NOTAS_FISCAIS_ORDEM ON NOTAS_FISCAIS (ORDEM_SERVICO_ID);

CREATE INDEX IX_NOTAS_FISCAIS_COMPETENCIA ON NOTAS_FISCAIS (CNPJ_PRESTADOR, COMPETENCIA, SITUACAO);

CREATE SEQUENCE SEQ_NOTA_FISCAL_NUMERO START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE;

CREATE TABLE ITENS_NOTA_FISCAL (
    ID                           VARCHAR2(36 CHAR)   NOT NULL,
    NOTA_FISCAL_ID               VARCHAR2(36 CHAR)   NOT NULL,
    NUMERO_ITEM                  NUMBER(10)     NOT NULL,
    TIPO                         VARCHAR2(20 CHAR)   NOT NULL,
    REFERENCIA_ID                VARCHAR2(36 CHAR)   NOT NULL,
    DESCRICAO                    VARCHAR2(200 CHAR)  NOT NULL,
    CODIGO_TRIBUTACAO_MUNICIPAL  VARCHAR2(20 CHAR),
    QUANTIDADE                   NUMBER(12,3)   NOT NULL,
    VALOR_UNITARIO               NUMBER(15,2)   NOT NULL,
    VALOR_TOTAL                  NUMBER(15,2)   NOT NULL,
    ALIQUOTA_ISS                 NUMBER(7,4)    NOT NULL,
    VALOR_ISS                    NUMBER(15,2)   NOT NULL,
    CONSTRAINT PK_ITENS_NOTA_FISCAL PRIMARY KEY (ID),
    CONSTRAINT UK_ITENS_NOTA_FISCAL_NUMERO UNIQUE (NOTA_FISCAL_ID, NUMERO_ITEM),
    CONSTRAINT FK_ITENS_NOTA_FISCAL_NOTA FOREIGN KEY (NOTA_FISCAL_ID) REFERENCES NOTAS_FISCAIS (ID),
    CONSTRAINT CK_ITENS_NOTA_FISCAL_TIPO CHECK (TIPO IN ('SERVICO', 'INSUMO')),
    CONSTRAINT CK_ITENS_NOTA_FISCAL_VALORES CHECK (QUANTIDADE > 0 AND VALOR_UNITARIO >= 0 AND VALOR_TOTAL >= 0 AND VALOR_ISS >= 0)
);
